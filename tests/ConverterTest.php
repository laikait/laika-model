}

/**
 * A driver with no Schema grammar behind it.
 *
 * Every built-in driver has one now, so this is the only way to reach the
 * converter's "no grammar for target" guard.
 */
final class GrammarlessDriver extends AbstractDriver implements DriverInterface
{
    public function getName(): string
    {
        return 'grammarless';
    }

    public function buildDsn(array $config): string
    {
        return 'sqlite::memory:';
    }
}
