    }

    /**
     * The block is cut on newlines, not on the delimiter — so a semicolon in
     * the data cannot split a row in half.
     */
    public function testCopyValueContainingASemicolonSurvives(): void
    {
        $sql = "COPY public.t (a) FROM stdin;\nnot; a; statement\n\\.\n";

        $this->assertSame(
            "INSERT INTO `t` (`a`) VALUES ('not; a; statement');",
            (new Converter('pgsql', 'mysql'))->convert($sql)
        );
    }

    /** A numeric column reads as a number, not as quoted digits. */
    public function testCopyEmitsNumericColumnsUnquoted(): void
    {
        $sql = "CREATE TABLE public.t (id integer NOT NULL, name character varying(10));\n"
            . "COPY public.t (id, name) FROM stdin;\n42\talice\n\\.\n";

        $this->assertStringContainsString(
            "VALUES (42, 'alice');",
            (new Converter('pgsql', 'mysql'))->convert($sql)
        );
    }

    /**
     * COPY spells booleans t/f. Reading only '1'/'true' turned every true into
     * a false — silently, since both are valid values.
     */
    public function testCopyBooleansAreNotSilentlyInverted(): void
    {
        $sql = "CREATE TABLE public.t (flag boolean);\n"
            . "COPY public.t (flag) FROM stdin;\nt\nf\n\\.\n";

        $out = (new Converter('pgsql', 'mysql'))->convert($sql);

        $this->assertStringContainsString('VALUES (1);', $out);
        $this->assertStringContainsString('VALUES (0);', $out);
    }

    /** The mode switch has to end, or every statement after it is eaten. */
    public function testSqlAfterACopyBlockStillConverts(): void
    {
        $sql = "COPY public.t (a) FROM stdin;\n1\n\\.\n"
            . "ALTER TABLE ONLY public.t ADD CONSTRAINT t_pkey PRIMARY KEY (a);";

        $out = (new Converter('pgsql', 'mysql'))->convert($sql);

        $this->assertStringContainsString('ALTER TABLE `t` ADD PRIMARY KEY (`a`);', $out);
    }

    /**
     * CSV is a different encoding. Decoding it with the text-format rules would
     * corrupt every row, so it is reported rather than guessed at.
     */
    public function testCopyInCsvFormatIsReportedNotMisdecoded(): void
    {
        $converter = new Converter('pgsql', 'mysql');
        $sql       = "COPY public.t (a, b) FROM stdin WITH (FORMAT csv);\n1,2\n\\.\n";

        $converter->convert($sql);

        $this->assertSame(
            Warning::LEVEL_PASSTHROUGH,
            $converter->report()->warnings()[0]->level
        );
    }

    /** COPY is PostgreSQL's; no other dialect should switch modes on it. */
    public function testCopyIsLeftAloneForNonPostgresSources(): void
    {
        $converter = new Converter('mysql', 'pgsql');

        $out = $converter->convert('COPY t FROM stdin;');

        $this->assertStringContainsString('COPY', $out);
    }

    // -----------------------------------------------------------------------
    // SQLite dump artefacts
    // -----------------------------------------------------------------------

    public function testPragmaIsDroppedRatherThanPassedThrough(): void
    {
        $converter = new Converter('sqlite', 'pgsql');

        // PRAGMA leads every sqlite3 .dump. Passing it through would reach the
        // target verbatim and fail there — no other engine has the statement.
        $this->assertSame('', $converter->convert('PRAGMA foreign_keys=OFF;'));
        $this->assertSame(
            Warning::LEVEL_SKIPPED,
            $converter->report()->warnings()[0]->level
        );
    }

    /** @dataProvider sqliteSequenceProvider */
    public function testSqliteInternalSequenceTableIsDropped(string $sql): void
    {
        $converter = new Converter('sqlite', 'pgsql');

        // sqlite_sequence is SQLite's own AUTOINCREMENT bookkeeping. It exists
        // on no other engine, so emitting it guarantees a failure.
        $this->assertSame('', $converter->convert($sql));
        $this->assertSame(
            Warning::LEVEL_SKIPPED,
            $converter->report()->warnings()[0]->level
        );
    }

    /** @return array<string,array{string}> */
    public static function sqliteSequenceProvider(): array
    {
        return [
            'insert' => ["INSERT INTO sqlite_sequence VALUES('users',3);"],
            'delete' => ['DELETE FROM sqlite_sequence;'],
            'quoted' => ['INSERT INTO "sqlite_sequence" VALUES(\'users\',3);'],
        ];
    }

    /** @return array<string,array{string,string}> */
    public static function roundTripProvider(): array
    {
        return [
            'integer'    => ['integer', '`c` INT NOT NULL'],
            'bigInteger' => ['bigInteger', '`c` BIGINT NOT NULL'],
            'string'     => ['string', '`c` VARCHAR(190) NOT NULL'],
