    /**
     * MySQL rejects AUTO_INCREMENT on a column that is not yet a key, and
     * pg_dump sets the sequence default *before* it adds the primary key. The
     * converter has to reorder them or the migration fails.
     */
    public function testAutoIncrementIsEmittedAfterThePrimaryKey(): void
    {
        $dump = <<<'SQL'
        CREATE TABLE public.users (
            id integer NOT NULL,
            username character varying(50) NOT NULL
        );
        ALTER TABLE ONLY public.users ALTER COLUMN id SET DEFAULT nextval('public.users_id_seq'::regclass);
        ALTER TABLE ONLY public.users ADD CONSTRAINT users_pkey PRIMARY KEY (id);
        SQL;

        $out = iterator_to_array((new Converter('pgsql', 'mysql'))->stream($dump), false);

        $primaryKey    = $this->indexOfStatement($out, 'ADD PRIMARY KEY');
        $autoIncrement = $this->indexOfStatement($out, 'AUTO_INCREMENT');

        $this->assertNotNull($primaryKey, 'The primary key was lost.');
        $this->assertNotNull($autoIncrement, 'The auto-increment was lost.');
        $this->assertGreaterThan(
            $primaryKey,
            $autoIncrement,
            'AUTO_INCREMENT must follow the PRIMARY KEY or MySQL rejects it'
        );
    }

